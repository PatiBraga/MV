SELECT  DESCRICAO
      , UNIDADE_INTERNACAO
      , TOTAL_SAIDAS
      , TOTAL_LEITOS
      , ROUND(TOTAL_SAIDAS/TOTAL_LEITOS,4)  PERCENTUAL
FROM (SELECT 'GIRO DE LEITO'  DESCRICAO
          , DS_UNID_INT   UNIDADE_INTERNACAO
          , SUM(1)    TOTAL_SAIDAS ,
          (SELECT COUNT(*) FROM LEITO L2 
              WHERE L.CD_UNID_INT = L2.CD_UNID_INT
              AND TP_SITUACAO = 'A' 
AND CD_TIP_ACOM NOT IN (SELECT CD_TIP_ACOM FROM TIP_ACOM WHERE  TP_ACOMODACAO = 'B') AND SN_EXTRA = 'N') * (TO_NUMBER(TO_CHAR(LAST_DAY(TO_DATE( $gCompet$  ,'MMYYYY')),'DD')) ) TOTAL_LEITOS
        FROM ATENDIME A, LEITO L, UNID_INT U
        WHERE A.CD_LEITO        = L.CD_LEITO
          AND L.CD_UNID_INT     = U.CD_UNID_INT
          AND A.TP_ATENDIMENTO  = 'I'
          AND L.TP_SITUACAO     = 'A'
          AND TO_CHAR((A.DT_ALTA),'MMYYYY') = $gCompet$ 
          AND A.CD_ATENDIMENTO_PAI IS NULL
          AND u.cd_unid_int !=14 -- HMulher o tulipa não tem leitos oficiais
        GROUP BY DS_UNID_INT,L.CD_UNID_INT
    order BY 2 
)