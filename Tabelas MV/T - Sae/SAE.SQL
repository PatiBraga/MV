SELECT
  ATENDIME.CD_ATENDIMENTO,
  ATENDIME.DT_ATENDIMENTO,
  S.DT_INICIO,
  S.DT_FIM,
  P.CD_PERGUNTA,
  P.DS_PERGUNTA,
  R.DS_RESPOSTA
FROM
  SAE_HISTORICO_ENFERMAGEM S
  INNER JOIN SAE_RESP_SELCND_HIST_ENFERMG RESP ON S.CD_HISTORICO_ENFERMAGEM = RESP.CD_HISTORICO_ENFERMAGEM
  INNER JOIN SAE_RESPOSTA_HISTORICO_ENFERMG R ON RESP.CD_RESPOSTA_HISTORICO = R.CD_RESPOSTA
  INNER JOIN SAE_PERGUNTA_HISTORICO_ENFERMG P ON RESP.CD_PERGUNTA_HISTORICO = P.CD_PERGUNTA
  INNER JOIN ATENDIME ON S.CD_ATENDIMENTO = ATENDIME.CD_ATENDIMENTO