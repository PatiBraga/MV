SELECT TUSS, CONVENIO, COUNT(*) AS qtd_duplicados
FROM REPASSE_IMAGEM_SW
WHERE (TUSS = '41101448' AND CONVENIO = '86')
   OR (TUSS = '40901386' AND CONVENIO = '40')
   OR (TUSS = '40901300' AND CONVENIO = '40')
   OR (TUSS = '40901386' AND CONVENIO = '8')
   OR (TUSS = '40901114' AND CONVENIO = '53')
   OR (TUSS = '40901114' AND CONVENIO = '26')
   OR (TUSS = '40901157' AND CONVENIO = '12')
   OR (TUSS = '41001060' AND CONVENIO = '12')
   OR (TUSS = '40901220' AND CONVENIO = '30')
   OR (TUSS = '40901220' AND CONVENIO = '35')
   OR (TUSS = '41101243' AND CONVENIO = '40')
GROUP BY TUSS, CONVENIO
HAVING COUNT(*) > 1;

